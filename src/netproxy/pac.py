"""A proxy auto-config (PAC) script generated from a router's rules.

Clients that read a PAC (browsers, OS proxy settings) then send only what
needs the proxy through it. A rule PAC JavaScript cannot express exactly
(a path, an IPv6 network, a custom callable) sends everything still
undecided to the proxy, which routes it exactly: the script errs towards the
proxy, never away from it.
"""

from __future__ import annotations

import json
from typing import Any, List, Optional

from ._route import Action, Route, Router
from .rules import (
    _All,
    AllOf,
    AnyOf,
    Host,
    HostRegex,
    Listener,
    Network,
    Not,
    Port,
    Scheme,
)

__all__ = ["generate_pac"]

_LISTENER = "proxy"

_HELPERS = """\
function _port(url) {
  var m = /^([a-z][a-z0-9+.-]*):\\/\\/(?:\\[[^\\]]*\\]|[^\\/:]*)(?::(\\d+))?/i.exec(url);
  if (!m) return 0;
  if (m[2]) return parseInt(m[2], 10);
  return m[1].toLowerCase() == "https" ? 443 : 80;
}
function _scheme(url) {
  return url.substring(0, url.indexOf(":")).toLowerCase();
}
function _ipv4(host) {
  return /^\\d{1,3}(\\.\\d{1,3}){3}$/.test(host);
}
"""


def _js(value: str) -> str:
    return json.dumps(value)


def _expression(matcher: Any) -> Optional[str]:
    """The matcher as a PAC JavaScript expression, or ``None`` if it has none."""
    if isinstance(matcher, _All):
        return "true"
    if isinstance(matcher, Host):
        terms = []
        for pattern in matcher.patterns:
            pattern = pattern.lower().rstrip(".")
            if pattern.startswith("."):
                terms.append(
                    f"(host == {_js(pattern[1:])} || dnsDomainIs(host, {_js(pattern)}))"
                )
            else:
                terms.append(f"shExpMatch(host, {_js(pattern)})")
        return "(" + " || ".join(terms) + ")"
    if isinstance(matcher, HostRegex):
        if matcher.flags & ~2:  # anything beyond re.IGNORECASE
            return None
        flags = "i" if matcher.flags else ""
        return f"new RegExp({_js('^(?:' + matcher.pattern + ')$')}, {_js(flags)}).test(host)"
    if isinstance(matcher, Port):
        terms = []
        for port in matcher.ports:
            if isinstance(port, range):
                if port.step != 1:
                    return None
                terms.append(
                    f"(_port(url) >= {port.start} && _port(url) < {port.stop})"
                )
            else:
                terms.append(f"_port(url) == {port}")
        return "(" + " || ".join(terms) + ")"
    if isinstance(matcher, Scheme):
        return (
            "("
            + " || ".join(f"_scheme(url) == {_js(s)}" for s in matcher.schemes)
            + ")"
        )
    if isinstance(matcher, Network):
        if any(n.version != 4 for n in matcher.networks):
            return None
        terms = [
            f"isInNet(host, {_js(str(n.network_address))}, {_js(str(n.netmask))})"
            for n in matcher.networks
        ]
        return "(_ipv4(host) && (" + " || ".join(terms) + "))"
    if isinstance(matcher, Listener):
        return "true" if _LISTENER in matcher.names else "false"
    if isinstance(matcher, (AllOf, AnyOf)):
        parts = [_expression(m) for m in matcher.matchers]
        if any(p is None for p in parts):
            return None
        joiner = " && " if isinstance(matcher, AllOf) else " || "
        return "(" + joiner.join(parts) + ")"  # type: ignore[arg-type]
    if isinstance(matcher, Not):
        inner = _expression(matcher.matcher)
        return None if inner is None else f"!{inner}"
    return None


def _outcome(route: Route, proxy: str, egress: Any) -> str:
    goes_direct = route.action is Action.DIRECT and (
        route.upstream == "direct" or (route.upstream is None and egress is None)
    )
    return "DIRECT" if goes_direct else f"PROXY {proxy}"


def generate_pac(router: Router, proxy: str, *, egress: Any = None) -> str:
    """A PAC script sending to ``proxy`` (``host:port``) every request
    ``router`` does not send straight to its destination.

    A route goes DIRECT in the script only when the proxy itself would connect
    directly: a DIRECT route whose upstream is ``"direct"``, or none with no
    ``egress``. Rules are evaluated in order, the default last.
    """
    if not isinstance(router, Router):
        raise TypeError("generate_pac needs a netproxy Router")
    lines: List[str] = [
        "// Generated by netproxy from its routing rules.",
        _HELPERS,
        "function FindProxyForURL(url, host) {",
        "  host = host.toLowerCase();",
    ]
    for rule in router.rules:
        outcome = _outcome(rule.route, proxy, egress)
        expression = _expression(rule.match)
        if expression is None:
            lines.append(
                f"  return {_js('PROXY ' + proxy)};  // a rule PAC cannot express"
            )
            lines.append("}")
            return "\n".join(lines) + "\n"
        lines.append(f"  if ({expression}) return {_js(outcome)};")
    lines.append(f"  return {_js(_outcome(router.default, proxy, egress))};")
    lines.append("}")
    return "\n".join(lines) + "\n"
